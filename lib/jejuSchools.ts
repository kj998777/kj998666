//    다만 다른 지역에도 흔한 이름이라, 시험 이름에 다른 시·도 이름(서울·부산·경기…)이 함께 있으면 제주로 보지 않는다
//    (예전 제보: "서울 중앙고"가 제주로 잡히면 안 됨).
// 3) "고/중"을 빼고 쓴 이름("남녕 1-1 기말", "대기 2학년")도, 제주에만 있는 학교 이름이면 제주로 본다.
