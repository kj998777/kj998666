const SHORTEN: [RegExp, string][] = [
  [/대학교사범대학부설/g, "사대부"],
  [/산업과학/g, "산과"],
  [/여자상업/g, "여상"],
  [/외국어/g, "외"],
  [/공업/g, "공"],
  [/과학/g, "과"],
  [/여자/g, "여"],
  [/고등학교$/, "고"],
  [/중학교$/, "중"],
];

function aliasesOf(full: string): string[] {
  const out = new Set<string>([full]);
  let s = full;
  for (const [re, to] of SHORTEN) s = s.replace(re, to);
  out.add(s); // 예: 제주여자고등학교 → 제주여고, 제주대학교사범대학부설고등학교 → 제주사대부고
  // 자주 쓰는 다른 줄임말
  if (s.endsWith("사대부고")) out.add(s.replace("사대부고", "대사대부고"));
  if (s.endsWith("여상고")) out.add(s.slice(0, -1)); // 제주여상
  if (s === "서귀포여고") out.add("서귀여고");
  if (s === "서귀포산과고") out.add("서귀포산업과학고");
  // 2026-09-28: 실제 시험 이름에 쓰이는 줄임말 추가. "제주제일고"는 보통 "제주일고"로 쓰는데 목록에 없어서
  // 제주일고 시험이 타 지역 시험으로 분류됐다(검토 배정에서 서울 중앙고와 같은 순위로 섞임).
  // "제주"·"서귀"가 붙은 줄임말만 넣는다("일고", "중앙고"처럼 다른 지역에도 있는 이름은 넣지 않음).
  if (s.startsWith("제주제일")) out.add(s.replace("제주제일", "제주일")); // 제주일고, 제주일중
  if (s.startsWith("서귀포")) out.add(s.replace("서귀포", "서귀")); // 서귀고, 서귀중, 서귀여중, 서귀산과고, 서귀대신중
  return Array.from(out);
}

