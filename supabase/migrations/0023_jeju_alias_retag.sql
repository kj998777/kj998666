-- 확인용: 지금 과외선생님 검토 배정 순서(위에서부터 먼저 나감). 남은_새문항이 0인 시험은 배정되지 않는다.
-- "제주"가 아니오인데 실제로는 제주 학교인 시험이 보이면, 시험 상세 화면의 "제주도 내 학교 시험"을
-- 체크해 주세요.
-- -------------------------------------------------------------------------
select e.name as 시험,
       case when e.is_jeju then '예' else '아니오' end as 제주,
       coalesce(e.school_level, '-') as 학교급,
       count(*) filter (where not ie.tutor_reviewed and not ie.review_confirmed) as 남은_새문항,
       count(*) as 전체문항
from public.exams e
join public.item_explanations ie on ie.exam_id = e.id
where e.status = '검수대기'
group by e.id, e.name, e.is_jeju, e.school_level
order by (count(*) filter (where not ie.tutor_reviewed and not ie.review_confirmed) = 0),
         e.is_jeju desc,
         case e.school_level when '고' then 0 when '중' then 1 else 2 end,
         e.name;
